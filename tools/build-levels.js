#!/usr/bin/env node
// Plans all 120 levels (2 languages x 3 difficulties x 20 levels) together so that
// words repeat as little as possible, and writes them to levels.js.
// Run it after changing puzzles.js:   node tools/build-levels.js
// (GitHub Actions also runs it before building the Android app.)
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");

global.window = { innerWidth: 400, addEventListener() {} };
global.document = { querySelector: () => null, addEventListener() {}, documentElement: {} };
global.navigator = {};
global.location = { protocol: "file:", hostname: "build" };
for (const f of ["config.js", "icons.js", "puzzles.js", "app.js"]) require(path.join(root, f));

const AXW = window.AXW;
const levels = {};
for (const lang of ["as", "en"]) {
  const t0 = Date.now();
  Object.assign(levels, AXW.planAll(lang, Number(process.env.ATTEMPTS || 80)));
  console.log(`${lang}: planned in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
}

// report how often words repeat
for (const lang of ["as", "en"]) {
  for (const D of AXW.DIFFS) {
    const uses = new Map();
    let back = 0, prev = new Set();
    for (let l = 1; l <= AXW.LEVELS; l++) {
      const ks = levels[`${lang}-${D.id}-${l}`].map((w) => w[0]);
      ks.forEach((k) => { uses.set(k, (uses.get(k) || 0) + 1); if (prev.has(k)) back++; });
      prev = new Set(ks);
    }
    const n = [...uses.values()].reduce((a, b) => a + b, 0);
    console.log(`${lang} ${D.id.padEnd(6)} ${n} words in 20 levels, ${uses.size} different, most used ${Math.max(...uses.values())}x, back-to-back repeats ${back}`);
  }
}

const out = "// Generated by tools/build-levels.js – do not edit by hand.\n" +
  "// Each level: [word id, answer, row, column, 0 = across / 1 = down].\n" +
  "window.LEVEL_PLAN = " + JSON.stringify({ made: new Date().toISOString().slice(0, 10), levels }) + ";\n";
fs.writeFileSync(path.join(root, "levels.js"), out);
console.log("wrote levels.js", (out.length / 1024).toFixed(0), "KB");
